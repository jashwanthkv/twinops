class DiscoveredComponent(BaseModel):
    """A logical software component extracted from the repository."""

    model_config = ConfigDict(populate_by_name=True)

    component_id: str = Field(default_factory=_new_id)
    run_id: str
    name: str
    component_type: ComponentType = Field(default=ComponentType.UNKNOWN)
    description: str | None = None
    primary_language: str | None = None
    root_paths: list[str] = Field(
        default_factory=list,
        description="Repo-relative directories that make up this component",
    )
    technologies: list[str] = Field(default_factory=list)
    exposed_ports: list[int] = Field(default_factory=list)
    environment_variables: list[str] = Field(
        default_factory=list,
        description="Names only — values must never be stored",
    )
    evidence: list[SourceEvidence] = Field(default_factory=list)
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)
    metadata: dict = Field(default_factory=dict)
    layer: str | None = Field(
        default=None,
        description="Architectural layer: edge|security|application|integration|data|messaging|ai|observability|platform|presentation|other",
    )


class DiscoveredRelationship(BaseModel):
    """A directed relationship between two discovered components."""

    model_config = ConfigDict(populate_by_name=True)

    relationship_id: str = Field(default_factory=_new_id)
    run_id: str
    source_component_id: str
    target_component_id: str
    relation_type: RelationType
    confidence: RelationshipConfidence = Field(
        default=RelationshipConfidence.MEDIUM
    )
    description: str | None = None
    evidence: list[SourceEvidence] = Field(default_factory=list)
    metadata: dict = Field(default_factory=dict)



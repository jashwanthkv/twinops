"""
aie/models.py — All shared Pydantic v2 data models for the AIE module.

Design notes:
  - Python 3.12 union syntax (X | Y) throughout.
  - model_config = ConfigDict(...)  — no legacy `class Config`.
  - All IDs are plain str (UUID strings generated by callers).
  - Timestamps are datetime objects (UTC, timezone-aware).
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field


# ──────────────────────────────────────────────────────────────────────────── #
# Helpers
# ──────────────────────────────────────────────────────────────────────────── #


def _now() -> datetime:
    return datetime.now(tz=timezone.utc)


def _new_id() -> str:
    return str(uuid.uuid4())


# ──────────────────────────────────────────────────────────────────────────── #
# Enumerations
# ──────────────────────────────────────────────────────────────────────────── #



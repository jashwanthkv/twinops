# ──────────────────────────────────────────────────────────────────────────── #
# Analysis run lifecycle
# ──────────────────────────────────────────────────────────────────────────── #


class AnalysisProgress(BaseModel):
    """Snapshot of progress for a running analysis."""

    model_config = ConfigDict(populate_by_name=True)

    stage: str = Field(description="Current pipeline stage name")
    stage_index: int = Field(ge=0, description="Zero-based stage index")
    total_stages: int = Field(ge=1)
    files_processed: int = Field(default=0, ge=0)
    files_total: int = Field(default=0, ge=0)
    message: str = Field(default="")
    percent_complete: float = Field(default=0.0, ge=0.0, le=100.0)


class AnalysisRun(BaseModel):
    """Lifecycle record for a single repository analysis job."""

    model_config = ConfigDict(populate_by_name=True, extra="allow")

    run_id: str = Field(default_factory=_new_id)
    application_id: str | None = None
    repo_url: str
    repo_ref: str = Field(default="HEAD", description="Branch, tag, or commit SHA")
    branch: str | None = None
    commit_hash: str | None = None
    user_email: str | None = None
    status: str = Field(
        default="pending",
        description="One of: pending | cloning | analysing | complete | failed",
    )
    created_at: datetime = Field(default_factory=_now)
    started_at: datetime | None = None
    completed_at: datetime | None = None
    error_message: str | None = None
    progress: AnalysisProgress | None = None
    result_summary: dict | None = Field(
        default=None,
        description="High-level counts / metadata once complete",
    )
    file_count: int = 0
    component_count: int = 0
    relationship_count: int = 0

    @property
    def analysis_id(self) -> str:
        return self.run_id

    @analysis_id.setter
    def analysis_id(self, val: str) -> None:
        self.run_id = val



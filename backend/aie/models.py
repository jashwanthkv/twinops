class AnalysisRequest(BaseModel):
    """Payload sent by the client to start a new analysis run."""

    model_config = ConfigDict(populate_by_name=True, extra="allow")

    repo_url: str = Field(description="HTTPS or SSH URL of the repository")
    repo_ref: str = Field(
        default="HEAD",
        description="Git ref (branch name, tag, or full commit SHA)",
    )
    branch: str | None = None
    application_id: str | None = None
    auth_token: str | None = None
    user_email: str | None = None
    options: dict = Field(
        default_factory=dict,
        description="Optional flags: skip_llm, max_files, etc.",
    )


class RepoAccessResult(BaseModel):
    """Result of a pre-flight repository access check."""

    model_config = ConfigDict(populate_by_name=True)

    repo_url: str
    is_accessible: bool
    is_private: bool | None = None
    default_branch: str | None = None
    clone_url: str | None = None
    error_message: str | None = None
    checked_at: datetime = Field(default_factory=_now)

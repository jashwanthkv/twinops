# File inventory
# ──────────────────────────────────────────────────────────────────────────── #


class FileEntry(BaseModel):
    """Metadata for one file found in the repository."""

    model_config = ConfigDict(populate_by_name=True)

    path: str = Field(description="Repo-relative POSIX path")
    size_bytes: int = Field(default=0, ge=0)
    extension: str = Field(default="")
    language: str | None = None
    category: FileCategory = Field(default=FileCategory.UNKNOWN)
    is_binary: bool = Field(default=False)
    encoding: str | None = None
    checksum_sha256: str | None = None


# ──────────────────────────────────────────────────────────────────────────── #
# Evidence
# ──────────────────────────────────────────────────────────────────────────── #


class SourceEvidence(BaseModel):
    """A single piece of evidence supporting an analysis conclusion."""

    model_config = ConfigDict(populate_by_name=True)

    evidence_type: EvidenceType
    source_path: str | None = Field(
        default=None, description="Repo-relative path of originating file"
    )
    snippet: str | None = Field(
        default=None, description="Short verbatim excerpt (no secrets)"
    )
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)
    notes: str | None = None


# ──────────────────────────────────────────────────────────────────────────── #
# Technology profiling
# ──────────────────────────────────────────────────────────────────────────── #


class LanguageInfo(BaseModel):
    """Statistics for one programming language found in the repo."""

    model_config = ConfigDict(populate_by_name=True)

    name: str
    file_count: int = Field(default=0, ge=0)
    line_count: int = Field(default=0, ge=0)
    byte_count: int = Field(default=0, ge=0)
    percentage: float = Field(default=0.0, ge=0.0, le=100.0)
    is_primary: bool = Field(default=False)


class FrameworkInfo(BaseModel):
    """A detected framework or major library."""

    model_config = ConfigDict(populate_by_name=True)

    name: str
    version: str | None = None
    ecosystem: str | None = Field(
        default=None, description="e.g. 'python', 'nodejs', 'java'"
    )
    evidence: list[SourceEvidence] = Field(default_factory=list)
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)


class TechnologyInfo(BaseModel):
    """An infrastructure technology or platform detected."""

    model_config = ConfigDict(populate_by_name=True)

    name: str
    category: str = Field(description="e.g. 'database', 'cloud', 'containerisation'")
    version: str | None = None
    evidence: list[SourceEvidence] = Field(default_factory=list)
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)


class EntryPoint(BaseModel):
    """A detected application entry point (main, CLI command, HTTP endpoint …)."""

    model_config = ConfigDict(populate_by_name=True)

    kind: str = Field(description="e.g. 'http_endpoint', 'cli_command', 'main_module'")
    path: str = Field(description="Repo-relative file path")
    identifier: str | None = Field(
        default=None,
        description="Function name, route path, command name, etc.",
    )
    description: str | None = None
    evidence: list[SourceEvidence] = Field(default_factory=list)


class TechnologyProfile(BaseModel):
    """Aggregated technology landscape of a repository."""

    model_config = ConfigDict(populate_by_name=True)

    run_id: str
    primary_language: str | None = None
    primary_framework: str | None = None
    language_primary_frameworks: dict[str, str] = Field(default_factory=dict)
    languages: list[LanguageInfo] = Field(default_factory=list)
    frameworks: list[FrameworkInfo] = Field(default_factory=list)
    technologies: list[TechnologyInfo] = Field(default_factory=list)
    entry_points: list[EntryPoint] = Field(default_factory=list)
    build_tools: list[str] = Field(default_factory=list)
    test_frameworks: list[str] = Field(default_factory=list)
    package_managers: list[str] = Field(default_factory=list)
    ci_cd_tools: list[str] = Field(default_factory=list)


